def _utc_now() -> datetime:
    return datetime.now(UTC)


def _iso(dt: datetime | None = None) -> str:
    value = dt or _utc_now()
    return value.astimezone(UTC).isoformat().replace("+00:00", "Z")


def _success(data: Any, message: str | None = None, *, status: int = 200) -> JSONResponse:
    payload: dict[str, Any] = {"success": True, "ok": True, "data": data}
    if message is not None:
        payload["message"] = message
    return JSONResponse(payload, status_code=status)


def _error(
    message: str,
    *,
    status: int = 400,
    field: str | None = None,
    data: Any | None = None,
) -> JSONResponse:
    payload: dict[str, Any] = {"success": False, "ok": False, "error": message, "message": message}
    if field is not None:
        payload["field"] = field
    if data is not None:
        payload["data"] = data
    return JSONResponse(payload, status_code=status)


def _normalize_api_path(path: str) -> str:
    if path.startswith("/api/admin/"):
        return path
    if path.startswith("/api/"):
        raw_path = path[len("/api/") :]
        if raw_path in {
            "users",
            "groups",
            "contacts",
            "products",
            "projects",
            "dashboard",
            "monitoring",
            "reports",
            "chat",
            "ai-assistant",
            "help",
            "incidents",
        } or raw_path.startswith(
            (
                "users/",
                "groups/",
                "contacts/",
                "products/",
                "projects/",
                "dashboard/",
                "monitoring/",
                "reports/",
                "chat/",
                "ai-assistant/",
                "help/",
                "incidents/",
            )
        ):
            return f"/api/admin/{raw_path}"
    return path


def _is_safe_filename(filename: str) -> bool:
    if not filename:
        return False
    if ".." in filename:
        return False
    if "/" in filename or "\\" in filename or ":" in filename:
        return False
    return filename == filename.strip() and "." in filename


def _make_png_bytes(label: str) -> bytes:
    image = Image.new("RGB", (1200, 700), (244, 247, 251))
    draw = ImageDraw.Draw(image)
    draw.rounded_rectangle((40, 40, 1160, 660), radius=36, fill=(59, 130, 246))
    draw.rounded_rectangle((70, 70, 1130, 630), radius=28, fill=(15, 23, 42))
    draw.text((120, 140), "SILO E2E", fill=(255, 255, 255))
    draw.text((120, 220), label, fill=(226, 232, 240))
    draw.text((120, 300), "Fixture image for next/image and uploads", fill=(148, 163, 184))
    buffer = io.BytesIO()
    image.save(buffer, format="PNG")
    return buffer.getvalue()


def _make_pdf_bytes(title: str, lines: list[str]) -> bytes:
    buffer = io.BytesIO()
    pdf = canvas.Canvas(buffer, pagesize=A4)
    pdf.setTitle(title)
    pdf.setFont("Helvetica-Bold", 22)
    pdf.drawString(48, 790, title)
    pdf.setFont("Helvetica", 12)
    y = 760
    for line in lines:
        pdf.drawString(48, y, line)
        y -= 18
    pdf.drawString(48, 80, "Generated by the SILO e2e fixture.")
    pdf.save()
    return buffer.getvalue()


def _sha256_hex(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


