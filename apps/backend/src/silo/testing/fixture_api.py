def _build_pdf_asset(label: str, lines: list[str]) -> dict[str, Any]:
    pdf_bytes = _make_pdf_bytes(label, lines)
    filename = f"{_slugify(label)}.pdf"
    return {
        "filename": filename,
        "bytes": pdf_bytes,
        "sha256": _sha256_hex(pdf_bytes),
        "byteSize": len(pdf_bytes),
        "url": f"/api/upload/serve/reports/{filename}",
    }


def _slugify(value: str) -> str:
    slug = re.sub(r"[^a-zA-Z0-9]+", "-", value.strip().lower())
    return slug.strip("-") or "report"


def _as_list(value: Any) -> list[Any]:
    return value if isinstance(value, list) else []


def _content_type_for_filename(filename: str) -> str:
    lower = filename.lower()
    if lower.endswith(".pdf"):
        return "application/pdf"
    if lower.endswith(".png"):
        return "image/png"
    if lower.endswith(".jpg") or lower.endswith(".jpeg"):
        return "image/jpeg"
    if lower.endswith(".webp"):
        return "image/webp"
    if lower.endswith(".gif"):
        return "image/gif"
    return "application/octet-stream"


def _strip_lucide_icon_class(icon: str | None) -> str:
    if not icon:
        return "users"
    match = re.fullmatch(r"icon-\[lucide--([^\]]+)\]", icon)
    if match:
        return match.group(1)
    return icon


def _group_user_count(groups: list[dict[str, Any]], users_by_email: dict[str, "AuthUserRecord"]) -> int:
    count = 0
    group_ids = {group["id"] for group in groups}
    for user in users_by_email.values():
        if any(str(membership.get("id") or "") in group_ids for membership in user.groups):
            count += 1
    return count


@dataclass(slots=True)
class AuthUserRecord:
    id: str
    name: str
    email: str
    password: str
    is_admin: bool
    is_active: bool = True
    image: str | None = None
    profile: dict[str, str] = field(default_factory=dict)
    groups: list[dict[str, str]] = field(default_factory=list)
    permissions: dict[str, list[str]] = field(default_factory=dict)
    preferences: dict[str, Any] = field(default_factory=dict)

    def public_user(self) -> dict[str, Any]:
        now = _iso()
        return {
            "id": self.id,
            "name": self.name,
            "email": self.email,
            "emailVerified": True,
            "image": self.image,
            "createdAt": now,
            "updatedAt": now,
            "isActive": self.is_active,
            "lastLogin": now,
        }

    def profile_payload(self) -> dict[str, Any]:
        return {
            "user": {
                "id": self.id,
                "name": self.name,
                "email": self.email,
                "isActive": self.is_active,
                "emailVerified": True,
                "image": self.image,
            },
            "userProfile": self.profile,
            "groups": self.groups,
            "permissions": self.permissions,
            "isAdmin": self.is_admin,
        }

    def preferences_payload(self) -> dict[str, Any]:
        return {"userPreferences": self.preferences}


