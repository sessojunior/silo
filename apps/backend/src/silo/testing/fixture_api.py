def _filter_chat_messages(
    messages: list[ChatMessageRecord],
    *,
    before: str | None = None,
    after: str | None = None,
    limit: int = 15,
    order: str = "desc",
) -> list[dict[str, Any]]:
    filtered = [message for message in messages if message.deleted_at is None]
    if before:
        filtered = [message for message in filtered if _iso(message.created_at) < before]
    if after:
        filtered = [message for message in filtered if _iso(message.created_at) > after]
    filtered.sort(key=lambda item: item.created_at, reverse=order == "desc")
    return [message.to_dto() for message in filtered[: max(1, limit)]]


