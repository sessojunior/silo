    def get_user_from_token(self, token: str | None) -> AuthUserRecord | None:
        if not token:
            return None
        user_id = self.sessions.get(token)
        if not user_id:
            return None
        for user in self.users_by_email.values():
            if user.id == user_id:
                return user
        return None

    def create_session(self, user: AuthUserRecord) -> str:
        token = f"sess-{uuid.uuid4()}"
        self.sessions[token] = user.id
        return token

    def clear_session(self, token: str | None) -> None:
        if token:
            self.sessions.pop(token, None)

